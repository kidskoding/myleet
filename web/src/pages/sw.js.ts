import type { APIRoute } from "astro";

// The service worker, emitted at build with a fresh version so each deploy updates it.
const VERSION = Date.now().toString(36);

const source = `// myleet service worker (generated by src/pages/sw.js.ts)
const VERSION = ${JSON.stringify(VERSION)};
const SHELL = "myleet-shell-" + VERSION;
const STATIC = "myleet-static";
const DATA = "myleet-data";
const CDN = "myleet-cdn";
const PAGES = ["/", "/app", "/onboarding", "/diagnostic", "/settings", "/signin", "/offline", "/learn", "/companies", "/mock", "/progress"];
const FILES = ["/data/catalog.json", "/palette-index.json", "/manifest.webmanifest", "/favicon.svg", "/icons/icon-192.png"];

async function precache() {
  const shell = await caches.open(SHELL);
  const stat = await caches.open(STATIC);
  const assets = new Set();
  await Promise.all(
    PAGES.map(async (p) => {
      try {
        const res = await fetch(p, { cache: "no-cache" });
        if (!res.ok) return;
        const html = await res.clone().text();
        for (const m of html.matchAll(/(?:href|src)="(\\/_astro\\/[^"]+)"/g)) assets.add(m[1]);
        for (const m of html.matchAll(/(?:import|from)\\s*\\(?["'](\\/_astro\\/[^"']+)["']/g)) assets.add(m[1]);
        await shell.put(p, res);
      } catch {}
    }),
  );
  await Promise.all(FILES.map((f) => shell.add(f).catch(() => {})));
  await Promise.all([...assets].map((a) => stat.match(a).then((hit) => hit || stat.add(a).catch(() => {}))));
}

self.addEventListener("install", (e) => e.waitUntil(precache()));

self.addEventListener("activate", (e) => {
  e.waitUntil(
    (async () => {
      for (const k of await caches.keys()) if (k.startsWith("myleet-shell-") && k !== SHELL) await caches.delete(k);
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (e) => {
  if (e.data === "skip-waiting") self.skipWaiting();
});

async function cacheFirst(req, name) {
  const cache = await caches.open(name);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok || res.type === "opaque") cache.put(req, res.clone());
  return res;
}

async function staleWhileRevalidate(req, name, e) {
  const cache = await caches.open(name);
  const hit = await cache.match(req);
  const net = fetch(req)
    .then((res) => {
      if (res.ok) cache.put(req, res.clone());
      return res;
    })
    .catch(() => hit);
  if (hit) {
    e.waitUntil(net);
    return hit;
  }
  return net;
}

// Data changes with every deploy, so a cached copy would show last deploy's companies and problems.
async function networkFirst(req, name) {
  const cache = await caches.open(name);
  try {
    const res = await fetch(req);
    if (res.ok) cache.put(req, res.clone());
    return res;
  } catch {
    return (await cache.match(req)) || Response.error();
  }
}

async function page(req) {
  const shell = await caches.open(SHELL);
  try {
    const res = await fetch(req);
    if (res.ok) shell.put(new URL(req.url).pathname, res.clone());
    return res;
  } catch {
    const path = new URL(req.url).pathname.replace(/\\/$/, "") || "/";
    return (
      (await shell.match(path)) ||
      (await shell.match(path + "/")) ||
      (path.startsWith("/u/") ? await shell.match("/u/_") : undefined) ||
      (await shell.match("/offline")) ||
      Response.error()
    );
  }
}

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    if (url.pathname.startsWith("/api/")) return;
    if (req.mode === "navigate") return e.respondWith(page(req));
    if (url.pathname.startsWith("/_astro/") || url.pathname.startsWith("/company-marks/")) return e.respondWith(cacheFirst(req, STATIC));
    if (url.pathname.startsWith("/data/") || url.pathname === "/palette-index.json" || url.pathname === "/runner-lib.json")
      return e.respondWith(networkFirst(req, DATA));
    return e.respondWith(staleWhileRevalidate(req, SHELL, e));
  }
  // Pyodide, its wheels and other versioned CDN files never change at a given URL.
  if (url.hostname === "cdn.jsdelivr.net" || url.hostname === "unpkg.com" || url.hostname === "files.pythonhosted.org")
    e.respondWith(cacheFirst(req, CDN));
});

self.addEventListener("notificationclick", (e) => {
  e.notification.close();
  e.waitUntil(
    (async () => {
      const all = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
      const open = all.find((c) => new URL(c.url).origin === location.origin);
      if (open) return open.focus();
      return self.clients.openWindow("/app");
    })(),
  );
});
`;

export const GET: APIRoute = () =>
  new Response(source, { headers: { "content-type": "text/javascript; charset=utf-8" } });
